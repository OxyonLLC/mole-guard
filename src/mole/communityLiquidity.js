/**
 * Per-wallet summary — total ever deposited/withdrawn, current status
 * (active or withdrawn-on-date), and which farm rounds this wallet has
 * historically staked its LP tokens into. Mirrors
 * getContributionLeaderboard()'s shape where reasonable. Pure function,
 * no I/O.
 */
export function summarizeCommunityLiquidity(events = COMMUNITY_LIQUIDITY_EVENTS) {
  const byWallet = new Map();
  const sorted = [...events].sort((a, b) => Date.parse(a.dateIso) - Date.parse(b.dateIso));

  for (const event of sorted) {
    const entry = byWallet.get(event.wallet) || {
      wallet: event.wallet,
      discordHandle: event.discordHandle,
      role: event.role,
      totalWinlewDepositedBaseUnits: 0n,
      totalWinlewWithdrawnBaseUnits: 0n,
      totalSolDepositedLamports: 0n,
      totalSolWithdrawnLamports: 0n,
      netLpTokenAmount: 0n,
      deposits: 0,
      withdrawals: 0,
      firstEventIso: event.dateIso,
      lastEventIso: event.dateIso,
      lastWithdrawIso: null,
    };
    const winlew = BigInt(event.winlewAmountBaseUnits);
    const sol = BigInt(event.solAmountLamports);
    const lp = BigInt(event.lpTokenAmount);

    if (event.type === LIQUIDITY_EVENT_TYPES.DEPOSIT) {
      entry.totalWinlewDepositedBaseUnits += winlew;
      entry.totalSolDepositedLamports += sol;
      entry.netLpTokenAmount += lp;
      entry.deposits += 1;
    } else {
      entry.totalWinlewWithdrawnBaseUnits += winlew;
      entry.totalSolWithdrawnLamports += sol;
      entry.netLpTokenAmount -= lp;
      entry.withdrawals += 1;
      if (entry.netLpTokenAmount <= 0n) entry.lastWithdrawIso = event.dateIso;
    }
    entry.lastEventIso = event.dateIso;
    byWallet.set(event.wallet, entry);
  }

  return [...byWallet.values()]
    .map((e) => ({
      ...e,
      totalWinlewDepositedBaseUnits: e.totalWinlewDepositedBaseUnits.toString(),
      totalWinlewWithdrawnBaseUnits: e.totalWinlewWithdrawnBaseUnits.toString(),
      totalSolDepositedLamports: e.totalSolDepositedLamports.toString(),
      totalSolWithdrawnLamports: e.totalSolWithdrawnLamports.toString(),
      netLpTokenAmount: e.netLpTokenAmount.toString(),
      status: e.netLpTokenAmount > 0n ? LIQUIDITY_PROVIDER_STATUSES.ACTIVE : LIQUIDITY_PROVIDER_STATUSES.WITHDRAWN,
      farmPrograms: FARM_PARTICIPATION[e.wallet] || [],
    }))
    .sort((a, b) => (BigInt(b.totalWinlewDepositedBaseUnits) > BigInt(a.totalWinlewDepositedBaseUnits) ? 1 : -1));
}
